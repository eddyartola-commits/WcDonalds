private void cargarImagenCajera() {

    javax.swing.ImageIcon icon = new javax.swing.ImageIcon(
            getClass().getResource("/Imagenes/cajer.png")
    );

    int anchoLabel = lblCajera.getWidth();
    int altoLabel = lblCajera.getHeight();

    int anchoImagen = icon.getIconWidth();
    int altoImagen = icon.getIconHeight();

    double escala = Math.min(
            (double) anchoLabel / anchoImagen,
            (double) altoLabel / altoImagen
    );

    int nuevoAncho = (int) (anchoImagen * escala);
    int nuevoAlto = (int) (altoImagen * escala);

    java.awt.Image imagenEscalada = icon.getImage().getScaledInstance(
            nuevoAncho,
            nuevoAlto,
            java.awt.Image.SCALE_SMOOTH
    );

    lblCajera.setIcon(new javax.swing.ImageIcon(imagenEscalada));
}
